// Orchestrator: profile generation, patch assembly, storage isolation, process lifecycle.
// Pure Node. It only drives the official `dsh` CLI; it never imports DSH packages.
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, rmSync, rmdirSync, writeFileSync } from 'node:fs'
import { basename, isAbsolute, join, resolve, sep } from 'node:path'

import {
  instanceDataRoot, orchestratorRoot, profileDir as profileDirOf, profilesRoot, resolveDshHome, resolveInstall,
} from './paths.mjs'
import {
  awaitReady as awaitReadyOf, runCli, spawnInstance, stop as stopOf, waitExit,
} from './process.mjs'
import { isAlive, killTree, probePort, waitUntilDead } from './probe.mjs'
import { Registry } from './registry.mjs'
import { disablePlugins, parsePatchRows, thirdPartyRows } from './profile-patch.mjs'

const MANIFEST = 'orchestrator.json'
const OVERLAY = 'orchestrator.overlay.yml'
const RESCUE_OVERLAY = 'orchestrator.rescue.yml'
const INIT_TIMEOUT_MS = 120_000

/** Storage rows isolated per instance (S2: shared credentials, isolated history). */
const STORAGE_ROWS = [
  { id: 'session-persistence-jsonl', dir: 'sessions' },
  { id: 'storage-json', dir: 'storages' },
]

/** YAML single-quoted scalar; forward slashes keep Windows paths literal. */
function yamlPath(p) {
  return `'${p.replace(/\\/g, '/').replace(/'/g, "''")}'`
}

/**
 * YAML scalar for an arbitrary id coming from a config file. Plain ids stay readable;
 * anything with YAML-significant characters is quoted so a crafted id cannot inject rows.
 */
function yamlScalar(value) {
  const text = String(value ?? '')
  return /^[A-Za-z0-9_.@/-]+$/.test(text) ? text : `'${text.replace(/'/g, "''")}'`
}

function deriveProfileName(workspacePath) {
  const hash = createHash('sha256').update(workspacePath).digest('hex').slice(0, 8)
  const slug = basename(workspacePath)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 20) || 'ws'
  return `ws-${slug}-${hash}`
}

/** Port from a served URL, or null. */
function parsePort(url) {
  if (!url) return null
  try {
    const port = Number(new URL(url).port)
    return Number.isFinite(port) && port > 0 ? port : null
  } catch {
    return null
  }
}

/** Path comparison that respects Windows case-insensitivity. */
function samePath(a, b) {
  if (!a || !b) return false
  const x = resolve(a)
  const y = resolve(b)
  return process.platform === 'win32' ? x.toLowerCase() === y.toLowerCase() : x === y
}

function unquote(value) {
  const text = String(value).trim()
  if (text.length >= 2 && ((text.startsWith("'") && text.endsWith("'")) || (text.startsWith('"') && text.endsWith('"')))) {
    return text.slice(1, -1)
  }
  return text
}

/**
 * Parse the flat entry list printed by `--dump-config`.
 * Only top-level rows (`- id:` at column 0, fields at 2 spaces) are collected;
 * rows nested inside a group config are indented deeper and ignored.
 * @returns {{id: string, name: string|null, disabled: string|null}[]}
 */
export function parseComposedEntries(text) {
  const rows = []
  let current
  for (const raw of String(text).split(/\r?\n/)) {
    const idMatch = /^- id:\s*(.+)$/.exec(raw)
    if (idMatch) {
      current = { id: unquote(idMatch[1]), name: null, disabled: null }
      rows.push(current)
      continue
    }
    if (!current) continue
    const nameMatch = /^ {2}name:\s*(.+)$/.exec(raw)
    if (nameMatch) { current.name = unquote(nameMatch[1]); continue }
    const disabledMatch = /^ {2}disabled:\s*(.+)$/.exec(raw)
    if (disabledMatch) current.disabled = disabledMatch[1].trim()
  }
  return rows
}

/** Official rows start with `@deepseek-ai/` or the `cordis:` builtin prefix. */
export function isThirdPartyRow(name) {
  if (!name) return false
  return !name.startsWith('@deepseek-ai/') && !name.startsWith('cordis:')
}

function renderRescueOverlay(rows) {
  const header = [
    '# Generated by dsh-orchestrator-core (rescue mode).',
    '# Disables every non-official plugin row so a broken third-party plugin cannot block boot.',
    '# Official @deepseek-ai/* rows are never touched.',
    '',
  ]
  if (rows.length === 0) return `${[...header, '[]', ''].join('\n')}`
  const body = rows.flatMap((row) => [`- id: ${row.id}`, '  disabled: true'])
  return `${[...header, ...body, ''].join('\n')}`
}

export class Orchestrator {
  /**
   * @param {object} [options]
   * @param {string} [options.home]          DSH home to share (default: $DSH_HOME or ~/.dsh)
   * @param {string} [options.dshExe]        desktop executable override
   * @param {number} [options.maxInstances]  concurrent instance cap (default 5)
   */
  constructor({ home, dshExe, maxInstances = 5 } = {}) {
    this.home = resolveDshHome(home)
    this.install = resolveInstall({ dshExe })
    this.maxInstances = maxInstances
    this.registry = new Registry(this.home)
  }

  /** Directory of an existing profile. */
  profileDir(profileName) {
    return profileDirOf(this.home, profileName)
  }

  /**
   * @typedef {object} Prepared
   * @property {string} profileName
   * @property {string} workspacePath
   * @property {string} home
   * @property {string} profileDir
   * @property {string} overlayPath
   * @property {string[]} patchFiles
   * @property {string} dataRoot
   * @property {boolean} created   profile was initialized by this call
   */

  /**
   * Resolve (and if needed create) a one-shot profile for a workspace.
   * Idempotent: an existing profile is reused unless `force`.
   *
   * @param {string} workspacePath absolute workspace directory
   * @param {object} [options]
   * @param {string} [options.name]        explicit profile name
   * @param {string} [options.baseProfile] template to initialize from (default `web`)
   * @param {boolean} [options.force]      recreate the profile from scratch
   * @param {string[]} [options.blacklist] loader-entry ids this workspace must not run;
   *                                       written as `disabled: true` rows into the overlay
   *                                       (ignored when `shareData` is true)
   * @returns {Promise<Prepared>}
   */
  async prepare(target, options = {}) {
    if ((options.mode ?? 'workspace') === 'rescue') return this.#prepareRescue(target, options)
    const ws = resolve(target)
    if (!isAbsolute(target)) {
      throw Object.assign(new Error(`workspacePath must be absolute, got: ${target}`), { code: 'EDSH_BAD_WORKSPACE' })
    }
    if (!existsSync(ws)) {
      throw Object.assign(new Error(`workspace does not exist: ${ws}`), { code: 'EDSH_BAD_WORKSPACE' })
    }

    const profileName = options.name ?? deriveProfileName(ws)
    const baseProfile = options.baseProfile ?? 'web'
    const dir = profileDirOf(this.home, profileName)

    if (options.force && existsSync(dir)) {
      this.#removeProfileDir(profileName)
    }

    let created = false
    if (!existsSync(join(dir, 'package.json'))) {
      await this.#initializeProfile(profileName, baseProfile)
      created = true
    }

    const storage = this.#prepareStorage(profileName, dir, options.shareData === true, options.blacklist ?? [])
    const prepared = {
      profileName,
      workspacePath: ws,
      home: this.home,
      profileDir: dir,
      overlayPath: storage.overlayPath,
      patchFiles: storage.patchFiles,
      dataRoot: storage.dataRoot,
      shareData: storage.shareData,
      blacklist: options.shareData === true ? [] : [...(options.blacklist ?? [])],
      owned: true,
      mode: 'workspace',
      createdAt: new Date().toISOString(),
      created,
    }
    writeFileSync(join(dir, MANIFEST), JSON.stringify(prepared, null, 2), 'utf8')
    return prepared
  }

  /**
   * Launch a prepared instance. Accepts a `Prepared` object or a profile name
   * (resolved through the manifest written by {@link prepare}).
   *
   * Always forces `--port 0 --no-open`.
   */
  launch(preparedOrName, options = {}) {
    const prepared = typeof preparedOrName === 'string'
      ? this.#readManifest(preparedOrName)
      : preparedOrName
    if (!prepared?.profileName) {
      throw Object.assign(new Error('launch() needs a Prepared object or a profile name'), { code: 'EDSH_BAD_PREPARED' })
    }

    this.registry.reload()
    const live = this.registry.instances.filter((record) => isAlive(record.pid))
    const duplicate = live.find((record) => record.profileName === prepared.profileName)
    if (duplicate) {
      throw Object.assign(
        new Error(
          `Profile "${prepared.profileName}" is already running (pid ${duplicate.pid}). `
          + 'Stop it first, or call reap() if it is a leftover entry.',
        ),
        { code: 'EDSH_ALREADY_RUNNING', pid: duplicate.pid },
      )
    }
    const limit = options.maxInstances ?? this.maxInstances
    if (live.length >= limit) {
      throw Object.assign(
        new Error(
          `Concurrent instance limit reached (${live.length}/${limit}). `
          + `Running: ${live.map((r) => `${r.profileName}#${r.pid}`).join(', ')}`,
        ),
        { code: 'EDSH_CONCURRENCY_LIMIT', limit, running: live.length },
      )
    }

    const patchFiles = Array.isArray(prepared.patchFiles)
      ? prepared.patchFiles
      : [join(profileDirOf(this.home, prepared.profileName), OVERLAY)]

    // A stale Prepared (e.g. its storage overlay was removed by a later in-place
    // rescue) must fail loudly here instead of inside DSH as an overlay ENOENT.
    const missing = patchFiles.filter((file) => !existsSync(file))
    if (missing.length > 0) {
      throw Object.assign(
        new Error(`Patch overlay missing: ${missing.join(', ')}. Re-run prepare() for "${prepared.profileName}".`),
        { code: 'EDSH_PATCH_FILE_MISSING', missing },
      )
    }

    const instance = spawnInstance({
      exe: this.install.exe,
      cliJs: this.install.cliJs,
      profileName: prepared.profileName,
      patchFiles,
      cwd: prepared.workspacePath,
      env: { DSH_HOME: prepared.home ?? this.home, ...options.env },
      extraArgs: options.extraArgs ?? [],
    })
    instance.prepared = prepared

    const record = {
      id: prepared.profileName,
      profileName: prepared.profileName,
      workspacePath: prepared.workspacePath,
      pid: instance.pid,
      url: null,
      port: null,
      startedAt: new Date().toISOString(),
      home: prepared.home ?? this.home,
      overlayPath: prepared.overlayPath ?? null,
      dataRoot: prepared.dataRoot ?? null,
    }
    this.registry.addInstance(record).trackSpawn(instance.pid, record).save()
    instance.registryRecord = record
    return instance
  }

  /** Resolve the served URL, or reject with captured output. Records URL/port. */
  async awaitReady(instance, options = {}) {
    const url = await awaitReadyOf(instance, options)
    const port = parsePort(url)
    if (instance?.profileName) {
      this.registry.reload()
      this.registry.updateInstance(instance.profileName, { url, port }).save()
    }
    return url
  }

  /**
   * Stop one instance.
   * @param {number|string|object} target pid, profile name, workspace path, or an instance handle
   */
  async stop(target, options = {}) {
    const { instance, record } = this.#resolveTarget(target)
    if (instance) {
      const info = await stopOf(instance, options)
      const dead = !isAlive(instance.pid)
      this.#finalizeStop(instance.profileName, instance.pid, dead)
      return { id: instance.profileName, pid: instance.pid, ...info, dead }
    }
    if (!record) {
      throw Object.assign(
        new Error('No running instance matches that pid / profile / workspace.'),
        { code: 'EDSH_INSTANCE_NOT_FOUND' },
      )
    }
    return this.#stopRecord(record, options)
  }

  /** All registered instances, with a liveness and port check. */
  async list({ probe = true } = {}) {
    this.registry.reload()
    const rows = []
    for (const record of this.registry.instances) {
      const alive = isAlive(record.pid)
      const row = { ...record, alive }
      if (probe && alive && record.port) row.portReachable = await probePort(record.port)
      rows.push(row)
    }
    return { count: rows.length, live: rows.filter((row) => row.alive).length, instances: rows }
  }

  /**
   * Reconcile the registry with reality:
   *  - drop records whose process is gone;
   *  - force-kill and forget PIDs we spawned that no longer have a live record.
   */
  async reap() {
    this.registry.reload()
    const summary = { staleRemoved: [], orphansKilled: [], stillAlive: [] }

    for (const record of this.registry.instances) {
      if (isAlive(record.pid)) continue
      this.registry.removeInstance(record.id)
      summary.staleRemoved.push({ id: record.id, pid: record.pid })
    }

    const liveIds = new Set(
      this.registry.instances.filter((record) => isAlive(record.pid)).map((record) => record.id),
    )
    for (const entry of this.registry.ledger) {
      if (!liveIds.has(entry.id) && isAlive(entry.pid)) {
        await killTree(entry.pid)
        const dead = await waitUntilDead(entry.pid, 5_000)
        if (dead) summary.orphansKilled.push({ pid: entry.pid, id: entry.id })
        else summary.stillAlive.push({ pid: entry.pid, id: entry.id })
      }
      if (!isAlive(entry.pid)) this.registry.untrackSpawn(entry.pid)
    }

    this.registry.saveOrPurge()
    summary.registered = this.registry.instances.length
    return summary
  }

  /** Stop every instance this manager knows about, then sweep leftovers. */
  async killAll(options = {}) {
    this.registry.reload()
    const stopped = []
    for (const record of this.registry.instances) {
      stopped.push(await this.#stopRecord(record, options))
    }
    for (const entry of this.registry.ledger) {
      if (isAlive(entry.pid)) {
        await killTree(entry.pid)
        await waitUntilDead(entry.pid, 5_000)
      }
      this.registry.untrackSpawn(entry.pid)
    }
    this.registry.save()

    const remaining = this.registry.instances.length
    let purged = false
    if (options.purge && remaining === 0 && this.registry.isEmpty) {
      this.registry.purge()
      purged = true
    }
    return { stopped, remaining, purged }
  }

  /**
   * Rescue shortcut: prepare in rescue mode, launch, and wait for the URL.
   * @param {string} target workspace path, or an existing (possibly broken) profile name
   */
  async rescue(target, options = {}) {
    const prepared = await this.prepare(target, { ...options, mode: 'rescue' })
    const instance = this.launch(prepared)
    try {
      const url = await this.awaitReady(instance, options)
      return { prepared, instance, url }
    } catch (error) {
      await this.stop(instance).catch(() => {})
      throw error
    }
  }

  /**
   * Remove the generated profile and its isolated data.
   * Only touches paths this class owns; refuses anything outside them.
   */
  dispose(preparedOrName) {
    const prepared = typeof preparedOrName === 'string'
      ? this.#readManifest(preparedOrName, { optional: true })
      : preparedOrName
    const profileName = prepared?.profileName ?? (typeof preparedOrName === 'string' ? preparedOrName : undefined)
    if (!profileName) return { removedProfile: false, removedData: false }

    // In-place rescue borrows the user's own profile: never delete it, only our files.
    if (prepared && prepared.owned === false) {
      const dir = profileDirOf(this.home, profileName)
      const removedFiles = [OVERLAY, RESCUE_OVERLAY, MANIFEST]
        .map((name) => join(dir, name))
        .filter((file) => this.#isInside(file, dir) && existsSync(file))
      for (const file of removedFiles) rmSync(file, { force: true })
      return { removedProfile: false, removedData: false, removedFiles: removedFiles.length, inPlace: true }
    }

    const removedProfile = this.#removeProfileDir(profileName)
    const dataRoot = instanceDataRoot(this.home, profileName)
    let removedData = false
    if (this.#isInside(dataRoot, orchestratorRoot(this.home))) {
      rmSync(dataRoot, { recursive: true, force: true })
      removedData = true
    }
    // Prune the namespace root once it is empty, so a dispose leaves no residue.
    try { rmdirSync(orchestratorRoot(this.home)) } catch {}
    return { removedProfile, removedData }
  }

  // ---------------------------------------------------------------- internals

  /**
   * Inspect a profile's OWN patch file. Deliberately file-based rather than
   * `--dump-config`: the CLI refuses to load any profile named `desktop`, and
   * third-party plugins a user installs live in this file anyway.
   */
  inspect(target) {
    const profileName = typeof target === 'string' ? target.trim() : target?.profileName
    if (!profileName) {
      throw Object.assign(new Error('inspect() needs a profile name'), { code: 'EDSH_BAD_TARGET' })
    }
    const dir = profileDirOf(this.home, profileName)
    if (!existsSync(join(dir, 'package.json'))) {
      throw Object.assign(new Error(`Profile "${profileName}" not found under ${this.home}`), { code: 'EDSH_NO_PROFILE' })
    }
    const file = join(dir, 'cordis.patch.yml')
    const text = existsSync(file) ? readFileSync(file, 'utf8') : ''
    return {
      profileName,
      profileDir: dir,
      file,
      exists: existsSync(file),
      rows: parsePatchRows(text),
      thirdParty: thirdPartyRows(text),
    }
  }

  /** Disable plugins in a profile's own patch file. Always backs up first. */
  disable(target, ids) {
    const inspected = this.inspect(target)
    const result = disablePlugins(inspected.profileDir, ids)
    return { profileName: inspected.profileName, ...result }
  }

  /**
   * Rescue mode: derive a profile whose third-party rows are all disabled.
   * Works either on an existing profile (rescue in place) or by creating a
   * dedicated `*-rescue` profile for a workspace.
   */
  async #prepareRescue(target, options = {}) {
    const looksLikePath = typeof target === 'string'
      && (isAbsolute(target) || target.includes('/') || target.includes('\\'))
    let profileName
    let dir
    let workspacePath
    let created = false
    let owned = true

    if (!looksLikePath) {
      profileName = String(target ?? '').trim()
      if (!profileName) {
        throw Object.assign(new Error('rescue() needs a workspace path or an existing profile name'), { code: 'EDSH_BAD_TARGET' })
      }
      if (profileName.toLowerCase() === 'desktop') {
        throw Object.assign(
          new Error(
            'The "desktop" profile is managed exclusively by the Electron app and cannot be booted by the CLI. '
            + 'Rescue it through a sibling profile instead (see bin/rescue.mjs).',
          ),
          { code: 'EDSH_RESERVED_PROFILE' },
        )
      }
      owned = false
      dir = profileDirOf(this.home, profileName)
      if (!existsSync(join(dir, 'package.json'))) {
        throw Object.assign(
          new Error(`Profile "${profileName}" not found under ${this.home}`),
          { code: 'EDSH_NO_PROFILE' },
        )
      }
      const manifest = this.#readManifest(profileName, { optional: true })
      workspacePath = resolve(options.workspacePath ?? manifest?.workspacePath ?? process.cwd())
    } else {
      workspacePath = resolve(target)
      if (!isAbsolute(target)) {
        throw Object.assign(new Error(`workspacePath must be absolute, got: ${target}`), { code: 'EDSH_BAD_WORKSPACE' })
      }
      if (!existsSync(workspacePath)) {
        throw Object.assign(new Error(`workspace does not exist: ${workspacePath}`), { code: 'EDSH_BAD_WORKSPACE' })
      }
      profileName = options.name ?? `${deriveProfileName(workspacePath)}-rescue`
      dir = profileDirOf(this.home, profileName)
      if (options.force && existsSync(dir)) this.#removeProfileDir(profileName)
      if (!existsSync(join(dir, 'package.json'))) {
        await this.#initializeProfile(profileName, options.baseProfile ?? 'web')
        created = true
      }
    }

    // Rescue shares the host's sessions/storages by default: a rescued user must
    // still see their own history. Pass `shareData: false` to isolate instead.
    const storage = this.#prepareStorage(profileName, dir, options.shareData !== false)

    // 1. Enumerate the composed rows without the rescue layer.
    //    `--dump-config` never mounts, so a hanging/broken plugin cannot block this.
    const baseDump = await this.#dumpConfig(profileName, storage.patchFiles, workspacePath)
    const entries = parseComposedEntries(baseDump.stdout)
    const thirdParty = entries.filter((row) => isThirdPartyRow(row.name) && row.id)
    const extraIds = (options.disableIds ?? []).filter((id) => !thirdParty.some((row) => row.id === id))
    const rowsToDisable = [...thirdParty, ...extraIds.map((id) => ({ id, name: '(explicit)' }))]

    // 2. Write the rescue layer.
    const rescuePath = join(dir, RESCUE_OVERLAY)
    writeFileSync(rescuePath, renderRescueOverlay(rowsToDisable), 'utf8')

    // 3. Verify the layer actually landed — a missed patch id is only a warning at boot.
    const patchFiles = [...storage.patchFiles, rescuePath]
    const finalDump = await this.#dumpConfig(profileName, patchFiles, workspacePath)
    const after = parseComposedEntries(finalDump.stdout)
    const notDisabled = rowsToDisable
      .map((row) => row.id)
      .filter((id) => {
        const row = after.find((entry) => entry.id === id)
        return !row || row.disabled !== 'true'
      })

    const prepared = {
      profileName,
      workspacePath,
      home: this.home,
      profileDir: dir,
      overlayPath: storage.overlayPath,
      rescuePath,
      patchFiles,
      dataRoot: storage.dataRoot,
      shareData: storage.shareData,
      owned,
      mode: 'rescue',
      createdAt: new Date().toISOString(),
      created,
      rescue: {
        thirdParty: thirdParty.map((row) => ({ id: row.id, name: row.name })),
        disabledIds: rowsToDisable.map((row) => row.id),
        verified: notDisabled.length === 0,
        notDisabled,
        totalRows: entries.length,
      },
    }
    writeFileSync(join(dir, MANIFEST), JSON.stringify(prepared, null, 2), 'utf8')
    return prepared
  }

  async #dumpConfig(profileName, patchFiles, cwd) {
    const args = [profileName]
    for (const file of patchFiles) args.push('--patch', file)
    args.push('--dump-config')
    return runCli({
      exe: this.install.exe,
      cliJs: this.install.cliJs,
      args,
      cwd,
      env: { DSH_HOME: this.home },
      timeoutMs: 60_000,
    })
  }

  /** Normalise pid / profile name / workspace path / instance handle. */
  #resolveTarget(target) {
    const bad = () => Object.assign(
      new Error('stop() needs a pid, profile name, workspace path, or an instance handle'),
      { code: 'EDSH_BAD_TARGET' },
    )
    if (target === null || target === undefined) throw bad()
    if (typeof target === 'object' && target.child) return { instance: target }

    this.registry.reload()
    if (typeof target === 'number') {
      const record = this.registry.instances.find((row) => row.pid === target)
      return { record: record ?? { id: `pid-${target}`, pid: target } }
    }
    if (typeof target === 'object') {
      if (typeof target.pid === 'number') return this.#resolveTarget(target.pid)
      if (typeof target.profileName === 'string') return this.#resolveTarget(target.profileName)
      if (typeof target.id === 'string') return { record: this.registry.get(target.id) }
      throw bad()
    }
    if (typeof target === 'string') {
      const looksLikePath = isAbsolute(target) || target.includes('/') || target.includes('\\')
      if (looksLikePath) {
        return { record: this.registry.instances.find((row) => samePath(row.workspacePath, target)) }
      }
      return { record: this.registry.instances.find((row) => row.profileName === target || row.id === target) }
    }
    throw bad()
  }

  async #stopRecord(record, { timeoutMs = 8_000 } = {}) {
    const { pid } = record
    let forced = false
    if (isAlive(pid)) {
      try { process.kill(pid) } catch {}
      await waitUntilDead(pid, Math.min(timeoutMs, 3_000))
      if (isAlive(pid)) {
        forced = true
        await killTree(pid)
        await waitUntilDead(pid, 5_000)
      }
    }
    const dead = !isAlive(pid)
    this.#finalizeStop(record.id, pid, dead)
    return { id: record.id, profileName: record.profileName, pid, forced, dead }
  }

  #finalizeStop(instanceId, pid, dead) {
    this.registry.removeInstance(instanceId)
    if (dead) this.registry.untrackSpawn(pid)
    this.registry.saveOrPurge()
  }

  /**
   * Decide whether this instance isolates sessions/storages.
   * `shareData: true` keeps the host's `$DSH_HOME/sessions` + `storages` so a
   * rescued user still sees their own history — the whole point of rescue.
   */
  #prepareStorage(profileName, dir, shareData, blacklist = []) {
    const overlayPath = join(dir, OVERLAY)
    if (shareData) {
      rmSync(overlayPath, { force: true })
      return { overlayPath: null, patchFiles: [], dataRoot: null, shareData: true }
    }
    const dataRoot = instanceDataRoot(this.home, profileName)
    writeFileSync(overlayPath, this.#renderOverlay(dataRoot, blacklist), 'utf8')
    mkdirSync(dataRoot, { recursive: true })
    return { overlayPath, patchFiles: [overlayPath], dataRoot, shareData: false }
  }

  #renderOverlay(dataRoot, blacklist = []) {
    const lines = [
      '# Generated by dsh-orchestrator-core. Do not edit by hand.',
      `# workspace isolation: S2 (shared credentials, per-workspace history)`,
      '',
    ]
    for (const row of STORAGE_ROWS) {
      lines.push(`- id: ${row.id}`)
      lines.push('  config:')
      lines.push(`    root: ${yamlPath(join(dataRoot, row.dir))}`)
    }
    // Workspace blacklist: rows this workspace must never run. Patches apply in order,
    // so these later top-level rows shadow whatever the bundle/patch layers inserted.
    // Applied to the isolated instance too, so a spawned environment obeys the same list
    // as the in-process single-open mode.
    if (blacklist.length > 0) {
      lines.push('', '# workspace blacklist (from single-mode.json)')
      for (const id of blacklist) {
        lines.push(`- id: ${yamlScalar(id)}`)
        lines.push('  disabled: true')
      }
    }
    lines.push('')
    return lines.join('\n')
  }

  async #initializeProfile(profileName, baseProfile) {
    // `--from-default-profile` initializes, `--dump-config` makes it exit without booting.
    // The web template can exit non-zero on unrelated schema warnings, so the
    // profile directory — not the exit code — decides success.
    const result = await runCli({
      exe: this.install.exe,
      cliJs: this.install.cliJs,
      args: [profileName, '--from-default-profile', baseProfile, '--dump-config'],
      cwd: this.home,
      env: { DSH_HOME: this.home },
      timeoutMs: INIT_TIMEOUT_MS,
    })
    const dir = profileDirOf(this.home, profileName)
    if (!existsSync(join(dir, 'package.json'))) {
      throw Object.assign(
        new Error(
          `Failed to initialize profile "${profileName}" from template "${baseProfile}" `
          + `(exit=${result.code}).\nstderr tail:\n${result.stderr.trimEnd().split('\n').slice(-15).join('\n')}`,
        ),
        { code: 'EDSH_PROFILE_INIT_FAILED' },
      )
    }
    return { dir, exitCode: result.code }
  }

  #readManifest(profileName, { optional = false } = {}) {
    const dir = profileDirOf(this.home, profileName)
    const file = join(dir, MANIFEST)
    if (!existsSync(file)) {
      if (optional) return undefined
      throw Object.assign(
        new Error(`No orchestrator manifest for profile "${profileName}". Run prepare() first.`),
        { code: 'EDSH_NO_MANIFEST' },
      )
    }
    return JSON.parse(readFileSync(file, 'utf8'))
  }

  #isInside(target, root) {
    const t = resolve(target)
    const r = resolve(root)
    return t.startsWith(r + sep) && t !== r
  }

  #removeProfileDir(profileName) {
    const dir = profileDirOf(this.home, profileName)
    if (!this.#isInside(dir, profilesRoot(this.home))) return false
    if (!existsSync(dir)) return false
    rmSync(dir, { recursive: true, force: true })
    return true
  }
}

